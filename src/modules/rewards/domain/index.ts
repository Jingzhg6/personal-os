export type PurchaseProblem =
  | "insufficient_active"
  | "insufficient_level"
  | "insufficient"
  | "not_enough_value"
  | "overpay"
  | "currency_not_accepted";

export interface RewardPurchase {
  canRedeem: boolean;
  activeXpToSpend: number;
  levelXpToSpend: number;
  /** Purchasing units the payment is worth. */
  purchaseValue: number;
  /** Units still missing (0 when the payment covers the price). */
  remainingPurchaseValue: number;
  problem: PurchaseProblem | null;
}

/**
 * How a reward would be paid. Deterministic and shared by the store preview and the server, which
 * recomputes it inside the redemption transaction with fresh balances.
 *
 *  - active_first: as much Active XP as possible, the rest in whole Level XP.
 *  - level_first:  as much Level XP as needed or available, the rest in Active XP.
 *  - custom:       exactly the amounts given; they must cover the price without overpaying by a
 *                  whole unit of either currency.
 */
export function calculateRewardPurchase(
  reward: { value: number; payWithActive: boolean; payWithLevel: boolean },
  balances: { spendableActiveXp: number; spendableLevelXp: number },
  payment: Payment,
): RewardPurchase {
  const rate = REWARD_XP_RATES;
  const activeBalance = reward.payWithActive ? Math.max(0, balances.spendableActiveXp) : 0;
  const levelBalance = reward.payWithLevel ? Math.max(0, balances.spendableLevelXp) : 0;

  let active: number;
  let level: number;
  if (payment.strategy === "custom") {
    active = payment.activeXp;
    level = payment.levelXp;
  } else if (payment.strategy === "active_first") {
    const uncovered = Math.max(0, reward.value - activeBalance * rate.active);
    level = reward.payWithLevel ? Math.ceil(uncovered / rate.level) : 0;
    active = Math.max(0, Math.ceil((reward.value - level * rate.level) / rate.active));
    if (!reward.payWithActive) active = 0;
  } else {
    level = reward.payWithLevel ? Math.min(levelBalance, Math.ceil(reward.value / rate.level)) : 0;
    active = reward.payWithActive
      ? Math.max(0, Math.ceil((reward.value - level * rate.level) / rate.active))
      : 0;
  }

  const purchaseValue = active * rate.active + level * rate.level;
  const result = (problem: PurchaseProblem | null): RewardPurchase => ({
    canRedeem: problem === null,
    activeXpToSpend: active,
    levelXpToSpend: level,
    purchaseValue,
    remainingPurchaseValue: Math.max(0, reward.value - purchaseValue),
    problem,
  });

  if ((active > 0 && !reward.payWithActive) || (level > 0 && !reward.payWithLevel)) {
    return result("currency_not_accepted");
  }
  if (purchaseValue < reward.value) {
    return result(payment.strategy === "custom" ? "not_enough_value" : "insufficient");
  }
  if (
    payment.strategy === "custom" &&
    ((active > 0 && purchaseValue - rate.active >= reward.value) ||
      (level > 0 && purchaseValue - rate.level >= reward.value))
  ) {
    return result("overpay");
  }
  if (active > activeBalance) return result("insufficient_active");
  if (level > levelBalance) return result("insufficient_level");
  return result(null);
}

