import { z } from "zod";

import { getStage, REWARD_XP_RATES, xpForLevel } from "@/modules/character/domain";

/*
 * Rewards: real-world treats the user buys with spendable XP. Spending never touches lifetime XP
 * — it only lowers the spendable balances (lifetime − spent), so the character level stays.
 *
 *   Reward store   — buy any time with Active XP, Level XP or a mix.
 *   Level reward   — free once the character reaches its level (claimable once).
 *   Early claim    — a level reward bought before reaching the level, with spendable Level XP
 *                    only; at most up to the end of the next stage band (see maxEarlyClaimLevel).
 */

export const rewardCategories = [
  "treat",
  "food",
  "entertainment",
  "shopping",
  "learning",
  "health",
  "experience",
  "travel",
  "other",
] as const;
export type RewardCategory = (typeof rewardCategories)[number];

/** Spendable balances: lifetime XP minus what the reward ledger spent. */
export interface XpBalances {
  lifetimeActiveXp: number;
  spendableActiveXp: number;
  lifetimeLevelXp: number;
  spendableLevelXp: number;
  /** Character level, from lifetime Level XP. */
  level: number;
}

/** The Active XP and Level XP prices of a value (a currency the reward refuses costs 0). */
export function rewardCosts(reward: {
  value: number;
  payWithActive: boolean;
  payWithLevel: boolean;
}): { activeXpCost: number; levelXpCost: number } {
  return {
    activeXpCost: reward.payWithActive ? Math.ceil(reward.value / REWARD_XP_RATES.active) : 0,
    levelXpCost: reward.payWithLevel ? Math.ceil(reward.value / REWARD_XP_RATES.level) : 0,
  };
}

export interface Reward {
  id: string;
  name: string;
  description: string | null;
  emoji: string | null;
  category: RewardCategory;
  /** Price in purchasing units. */
  value: number;
  payWithActive: boolean;
  payWithLevel: boolean;
  activeXpCost: number;
  levelXpCost: number;
  enabled: boolean;
  repeatable: boolean;
  maxRedemptions: number | null;
  realWorldCostCents: number | null;
  redemptionCount: number;
  /** Redemptions left (null: unlimited). */
  remaining: number | null;
  createdAt: Date;
}

/** How many more times a reward can be redeemed (null: unlimited). */
export function remainingRedemptions(
  reward: Pick<Reward, "repeatable" | "maxRedemptions">,
  redemptionCount: number,
): number | null {
  const limit = reward.repeatable ? reward.maxRedemptions : 1;
  return limit === null ? null : Math.max(0, limit - redemptionCount);
}

